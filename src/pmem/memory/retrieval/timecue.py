"""时间路由：判断一句问话是不是在问「时间 / 某一天 / 多久」。

**为什么要单独一层**：时间类问句（「上周咱们都干嘛了」「昨天那个会开多久」
「10 月 29 号是什么事」）和普通事实问句要的召回预算不是一回事——前者的答案往往
只有一两条（那一天的日记、当时那件事），给 40 条候选只是把 600 token 摊薄，把
真正那一天的那条挤到后面去。这里只做**识别**：确定性、零依赖、不调模型；
命中之后怎么收敛 k/budget 由 ``search.run_search`` 决定（默认 k≤8、budget≤600）。

**宁少报不多报**（和 ``temporal.py`` 的模糊词不猜是同一条纪律）：

- 明确的日期/时段词（今天、昨天、上周、去年、10月29日、3天前…）直接算命中；
- 「最近 / 上次 / 上回」单看太宽（「最近好吗」不一定是问时间），
  只在**短问句**（≤ ``SHORT_QUESTION_CHARS`` 字）或与其它明确时间词共现时才算命中；
- 含歧义的数量表达（「三天打鱼」「一年四季」）宁可漏，不硬收——漏了只是多给几条候选，
  误收会把普通问题也压成小预算。

这和 ``memory/temporal.py`` 的分工：那边关心「这条事实在什么时间成立」（打分用），
这边关心「这句问话是不是在问时间」（路由用），两者都只做词面判断，互不依赖。
"""

from __future__ import annotations

import re
import unicodedata

# 弱线索只在短问句里单独成立；长问句里它们必须和别的明确时间词一起出现。
SHORT_QUESTION_CHARS = 30

# 明确的时段/时间疑问词。选词标准：日常中文里基本只用来指时间的那一批。
# 「最近 / 上次 / 上回」故意不在这里（见 ``_WEAK_WORDS``）。
_STRONG_WORDS = (
    # 日
    "今天",
    "今日",
    "昨天",
    "昨日",
    "昨晚",
    "前天",
    "明天",
    "明日",
    "后天",
    "大前天",
    "大后天",
    "当天",
    # 周
    "上周",
    "上星期",
    "上个星期",
    "上礼拜",
    "这周",
    "本周",
    "这星期",
    "这个星期",
    "这礼拜",
    "下周",
    "下星期",
    "下个星期",
    "下礼拜",
    "上周末",
    "这周末",
    "周末",
    # 月
    "上个月",
    "上月",
    "这个月",
    "本月",
    "这月",
    "下个月",
    "下月",
    # 年
    "去年",
    "今年",
    "前年",
    "明年",
    # 回忆：指代某一次/某一段
    "那天",
    "那次",
    "那回",
    "当时",
    "那时候",
    "那会儿",
    "那阵子",
    # 时间疑问
    "多久",
    "多长时间",
    "什么时候",
    "啥时候",
    "啥时间",
    "哪年",
    "哪一年",
    "哪个月",
    "哪一天",
    "哪天",
    "几号",
    "几月",
    "星期几",
    "周几",
    "礼拜几",
    "几点",
    "几时",
    # 时段
    "前几天",
    "前两天",
    "这些天",
    "这几天",
    "这两天",
    "这段时间",
    "这段日子",
)

_WEAK_WORDS = ("最近", "近来", "上次", "上回", "上一次")

# 绝对日期：2026-11-05 / 2026/11/5 / 2026年10月29日 / 2026年10月（日可省）
_DATE_ABS = re.compile(
    r"(?<!\d)\d{4}\s*[-/.年]\s*\d{1,2}\s*[-/.月]\s*\d{1,2}\s*[日号]?"
)
# 只写了年份：「2019 年以来」「2026 年的总结」。
_YEAR_ONLY = re.compile(r"(?<!\d)\d{4}\s*年")
# 月日：10月29日 / 10月29号（不要求年份）
_MONTH_DAY = re.compile(r"(?<!\d)\d{1,2}\s*月\s*\d{1,2}\s*[日号]")
# 只写了日：29号。「3号线」「5号楼」这类不是日期，用后一个字排除。
_DAY_ONLY = re.compile(r"(?<!\d)\d{1,2}\s*[日号](?![号线楼层房桌车床位])")
# 星期：周三 / 周末 / 下周三 / 星期天 / 礼拜五
_WEEKDAY = re.compile(r"(?:上上|下下|上|下|本|这)?\s*(?:周|星期|礼拜)\s*[一二三四五六日天末]")

# 相对量词：「3天前」「两周前」「半个月前」「2019年以后」。
_NUM = r"[0-9零一二三四五六七八九十百千两半几数多]+"
_UNIT = r"(?:个)?\s*(?:天|日|周|星期|礼拜|个月|月|年|小时|钟头|分钟)"
_REL_AGO = re.compile(rf"{_NUM}\s*{_UNIT}\s*(?:以?前|之前)")
_REL_AFTER = re.compile(rf"{_NUM}\s*{_UNIT}\s*(?:以?后|之后)")
# 不带前后的数量词也常是时间题：「两周够不够」「半小时前的消息」「几个月了」。
# 只收周/月/小时这类不太会出现在非时间语境里的单位；「N 天 / N 年」交给带前缀后缀的
# 两条正则（「三天打鱼」「一年四季」不误收）。
_REL_SPAN = re.compile(rf"{_NUM}\s*(?:个)?\s*(?:周|星期|礼拜|个月|小时|钟头|分钟)")
# 「几天」「半年」这种带概数/半数的说法本身就是时间线索。
_REL_FEW = re.compile(rf"(?:几|半)\s*(?:天|日|年)")


def _norm(text: str) -> str:
    """全角→半角、压空白；只做检索用的轻量归一，不改原句。"""
    body = unicodedata.normalize("NFKC", str(text or ""))
    return re.sub(r"\s+", " ", body).strip()


def _explicit_cue(text: str) -> bool:
    """句子里有没有**明确**的时间线索（不含弱线索）。"""
    if any(word in text for word in _STRONG_WORDS):
        return True
    for pattern in (
        _DATE_ABS,
        _YEAR_ONLY,
        _MONTH_DAY,
        _DAY_ONLY,
        _WEEKDAY,
        _REL_AGO,
        _REL_AFTER,
        _REL_SPAN,
        _REL_FEW,
    ):
        if pattern.search(text):
            return True
    return False


def is_time_question(q: str) -> bool:
    """这句问话是不是在问时间（用于收紧检索的条数/预算）。

    纯词面判断、可重复：同一个句子永远得到同一个答案，不依赖今天几号、也不调模型。
    """
    text = _norm(q)
    if not text:
        return False
    if _explicit_cue(text):
        return True
    # 弱线索（最近/上次/上回）：单独出现时只在短问句里成立。
    # 「最近怎么样」是时间题；「最近我在想整个检索链路的参数要不要全部重新标定」不是。
    if any(word in text for word in _WEAK_WORDS):
        return len(text) <= SHORT_QUESTION_CHARS
    return False
