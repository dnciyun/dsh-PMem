"""「我说过的话」线索正则（0.33.0 放宽）。

0.32.0 只认十来个「你说过/你答应」的写法，外部靶场里 58 道真在问「助手说过什么」
的题，只命中 23 道——一大半是口语变体（你上回讲、你先前、你给自己、你那个…）。
0.33.0 放宽到 53/58，但**只保留「你」这个锚点**：省略「你」的「上次说/之前说」
会多命中 67 道用户事实题（「我上回说…」「上次说的夜班见闻，我还欠你几件」），
而只多找回 11 道，所以不采纳——宁可漏，也不能拿助手的话去顶用户陈述。

这个文件钉住两头：该命中的口语变体要命中；用户事实的典型问法不能命中。
"""

from __future__ import annotations

import unittest

from pmem.memory.retrieval.channels import ASSISTANT_VOICE_CLUES


def _hit(text: str) -> bool:
    return bool(ASSISTANT_VOICE_CLUES.search(text))


class CuePositiveCase(unittest.TestCase):
    def test_original_cues_still_hit(self) -> None:
        for text in (
            "你上次说自己晚上记东西那个身份叫什么",
            "你答应过我的事还记得吗",
            "你之前说的那套办法怎么用",
            "你的设定是什么",
        ):
            self.assertTrue(_hit(text), text)

    def test_colloquial_variants_hit(self) -> None:
        for text in (
            # 你上回讲（0.32 只认「你上回说」，漏了「讲」）
            "你上回讲自己整理记忆的三层柜时，说吵架的气话放在哪一层？",
            # 你先前 / 你给自己 / 你说自己
            "你先前给自己取的那个角色是啥，负责啥？",
            "你给自己安的台账角色具体咋回事？",
            "你说自己晚上记东西那个身份叫什么，按什么原则记？",
            # 你给我 / 你给了
            "你给我那两盆薄荷想的花牌标记分别是什么？",
            # 你那个 / 你这边 / 你当时
            "把你那个拆线头的三格按顺序报一下。",
            "你这边现在给到哪一步了？",
            "那次我们编的小纸船叫什么？你当时答应什么时候继续写什么？",
            # 你之前（不跟「说」）
            "你之前提议的三种颜色分别标什么？",
            # 你说 + 动词
            "你说平时叫我什么？赶截稿的时候又叫什么？",
            "你说给吧台东西分色的办法，各色标什么？",
            # 交付核对（助手答应过的东西后来交没交）
            "小店清单上次说延到哪天，后来到底交齐没有？",
            # 个人习惯 / 规矩 / 原则
            "你接悬疑故事前那个固定习惯，具体怎么做来着？",
            # 按你说的 / 照你的
            "按你说的办就行，那第一步是什么？",
            "我照你的三色法贴的，红蓝黄分别处理哪种东西？",
        ):
            self.assertTrue(_hit(text), text)


class CueNegativeCase(unittest.TestCase):
    """用户自己的话：绝不能因为放宽线索被打上「问助手」的标记。"""

    def test_user_own_words_are_not_cues(self) -> None:
        for text in (
            # 省略「你」的「上回说/之前说」——都是用户在说自己的事
            "我上回说下雨才考虑挪货架，当时已经挪了吗？",
            "上次说的夜班见闻，我还欠你几件？已经讲过哪件？",
            "之前说过的那批黄油箱，外面的封条数量我提过几种？",
            # 「跟你说岔过」是用户的记忆，不是问助手说过什么
            "我生日到底是哪天？之前好像还跟你说岔过。",
            # 请求句不是回忆（「你答应我嘛」是在要求，不是在问旧话）
            "你接电话了吗，刚才怎么不接",
        ):
            self.assertFalse(_hit(text), text)


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
